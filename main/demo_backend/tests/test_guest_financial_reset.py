    async def asyncTearDown(self):
        async with self.engine.begin() as db:
            for name in ("efhc_test","efhc_core","efhc_admin"):
                await db.execute(text(f"DROP SCHEMA IF EXISTS {name} CASCADE"))
        await self.engine.dispose()

    async def _scope(self,db):
        await db.execute(text(
            "SELECT set_config('neon.project_id',"
            "'fragrant-mountain-35143707',true)"
        ))
        await db.execute(text(
            "SELECT set_config('neon.branch_id',"
            "'br-winter-rice-zalqeb10',true)"
        ))

    async def _event(self,db,*,amount,direction,typ,reason,suffix):
        key=f"guest-3001:{suffix}"
        await db.execute(text("""
          INSERT INTO efhc_core.efhc_transfers_log
          (global_id,amount,direction,balance_type,reason,idempotency_key)
          VALUES (3001,:amount,:direction,:typ,:reason,:key)
        """),{"amount":amount,"direction":direction,
               "typ":typ,"reason":reason,"key":key})
        await db.execute(text("""
          INSERT INTO efhc_core.efhc_transfers_log
          (system_entity,amount,direction,balance_type,reason,idempotency_key)
          VALUES ('BANK_EFHC',:amount,:direction,'main',:reason,:key)
        """),{"amount":amount,
               "direction":"credit" if direction=="debit" else "debit",
               "reason":"mirror:"+reason,"key":"mirror:"+key})

    async def test_deposit_purchase_exchange_logout_restores_and_keeps_history(self):
        async with self.factory() as db:
            await self._scope(db)
            await self._event(db,amount=50,direction="credit",
                              typ="main",reason="demo_simulated_external_deposit",suffix="topup")
            await self._event(db,amount=100,direction="debit",
                              typ="bonus",reason="panel_activation",suffix="panel")
            await self._event(db,amount=30,direction="credit",
                              typ="main",reason="exchange_partial",suffix="exchange")
            await db.execute(text("""
              UPDATE efhc_core.users
              SET main_balance=980,bonus_balance=0,total_generated_kwh=1185.8816,
                  exchanged_kwh_total=31
              WHERE global_id=3001
            """))
            await db.execute(text("""
              UPDATE efhc_core.bank_balance SET balance=4998020
              WHERE key='EFHC_MAIN'
            """))
            await db.execute(text("""
              INSERT INTO efhc_core.panels
              (id,global_id,public_id,is_active,is_archived,generated_kwh,
               activated_at,expires_at,base_gen_per_sec,meta)
              VALUES (999999,3001,'PNL00999999',TRUE,FALSE,0,now(),
                      now()+interval '180 days',0.00000741,'{}'::jsonb)
            """))
            await db.commit()

        async with self.factory() as db:
            await self._scope(db)
            self.assertTrue(await release_guest(
                db,global_id="0000003001",resume_token=self.token
            ))
            await db.commit()

        async with self.factory() as db:
            await self._scope(db)
            row=(await db.execute(text("""
              SELECT main_balance,bonus_balance,total_generated_kwh,
                     exchanged_kwh_total,available_kwh
              FROM efhc_core.users WHERE global_id=3001
            """))).one()
            self.assertEqual(tuple(map(str,row)),
                ("900.00000000","100.00000000","1165.88160000","1.00000000","1164.88160000"))
            self.assertEqual(str((await db.execute(text(
                "SELECT balance FROM efhc_core.bank_balance WHERE key='EFHC_MAIN'"
            ))).scalar_one()),"4998000.00000000")
            self.assertEqual((await db.execute(text("""
                SELECT COUNT(*) FROM efhc_core.panels
                WHERE global_id=3001 AND is_active AND NOT is_archived
            """))).scalar_one(),5)
            self.assertEqual((await db.execute(text("""
                SELECT COUNT(*) FROM efhc_core.panels
                WHERE global_id=3001 AND is_archived
            """))).scalar_one(),10)
            tombstone=(await db.execute(text("""
                SELECT is_active,is_archived,meta->>'demo_reset_void'
                FROM efhc_core.panels WHERE id=999999
            """))).one()
            self.assertEqual(tombstone,(False,False,"true"))
            self.assertEqual((await db.execute(text("""
                SELECT COUNT(*) FROM efhc_core.efhc_transfers_log
                WHERE global_id=3001 AND reason='demo_reset'
            """))).scalar_one(),3)
            self.assertTrue(await reusable_starter_is_intact(db,3001))
            self.assertTrue(await reusable_starter_is_intact(db,3002))
            self.assertEqual((await db.execute(text("""
                SELECT COUNT(*) FROM efhc_test.guest_leases WHERE global_id=3001
            """))).scalar_one(),0)
            mass=(await db.execute(text("""
                SELECT (SELECT balance FROM efhc_core.bank_balance
                        WHERE key='EFHC_MAIN')+
                       (SELECT SUM(main_balance+bonus_balance)
                        FROM efhc_core.users)
            """))).scalar_one()
            self.assertEqual(int(mass),5000000)

    async def test_unmirrored_transfer_fails_closed_without_mutating_bank(self):
        async with self.factory() as db:
            await self._scope(db)
            await db.execute(text("""
                INSERT INTO efhc_core.efhc_transfers_log
                (global_id,amount,direction,balance_type,reason,idempotency_key)
                VALUES (3001,1,'credit','main','exchange_all','unmirrored')
            """))
            with self.assertRaises(GuestResetUnsafe):
                await reset_guest_economy(db,3001)
            await db.rollback()
        async with self.factory() as db:
            b=(await db.execute(text(
                "SELECT balance FROM efhc_core.bank_balance WHERE key='EFHC_MAIN'"
            ))).scalar_one()
            self.assertEqual(int(b),4998000)

    async def test_wrong_resume_token_cannot_release_or_reset(self):
        async with self.factory() as db:
            await self._scope(db)
            self.assertFalse(await release_guest(
                db,global_id="0000003001",resume_token="g"*48))
            await db.rollback()
        async with self.factory() as db:
            self.assertEqual((await db.execute(text(
                "SELECT COUNT(*) FROM efhc_test.guest_leases"
            ))).scalar_one(),1)


